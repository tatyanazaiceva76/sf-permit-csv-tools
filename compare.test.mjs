import assert from 'node:assert/strict';
import fs from 'node:fs';
import { compareSnapshots, selectComparisonRows, comparisonCSV } from './compare-core.mjs';
import { parseCSV } from './finder-core.mjs';
const header = 'permit_number,status,status_date,description,primary_address_flag,data_as_of\n';
const before = header + '1,filed,2026-10-01,restaurant,Y,2026-10-02\n2,issued,2026-09-01,kitchen,Y,2026-10-02\n';
const after = header + '1,issued,2026-10-20,restaurant,Y,2026-10-21\n3,filed,2026-10-01,cafe,Y,2026-10-21\n';
const result = compareSnapshots(before, after);
assert.deepEqual(result.counts, { only_later: 1, only_earlier: 1, changed: 1, unchanged: 0, ambiguous: 0 });
assert.deepEqual(result.rows.find(r => r.permit_number === '1').changed_fields, ['status', 'status_date']);
const asOfOnly = compareSnapshots(before, before.replaceAll('2026-10-02', '2026-10-25'));
assert.equal(asOfOnly.counts.unchanged, 2); assert.equal(selectComparisonRows(asOfOnly).length, 0);
const duplicate = compareSnapshots(before, after + '1,filed,2026-10-01,restaurant,Y,2026-10-21\n');
assert.equal(duplicate.counts.ambiguous, 1); assert.equal(duplicate.counts.changed, 0);
const exactDuplicate = compareSnapshots(before, before + '1,filed,2026-10-01,restaurant,Y,2026-10-02\n');
assert.equal(exactDuplicate.counts.unchanged, 2); assert.equal(exactDuplicate.later_stats.duplicateRows, 1);
const exclusions = compareSnapshots(before, before + '4,filed,2026-10-01,restaurant,N,2026-10-02\n,filed,2026-10-01,restaurant,Y,2026-10-02\n');
assert.equal(exclusions.later_stats.secondaryRows, 1); assert.equal(exclusions.later_stats.missingIdRows, 1);
assert.equal(exclusions.counts.only_later, 0);
const aliases = compareSnapshots('Permit Number,Current Status,Current Status Date\n1,FILED,10/1/2026\n', 'permit_number,status,status_date\n1,filed,2026-10-01T14:30:00.000\n');
assert.equal(aliases.counts.unchanged, 1);
assert.throws(() => compareSnapshots('permit_number\n1\n', after), /required columns/);
assert.throws(() => compareSnapshots('permit_number,status,current_status\n1,filed,filed\n', after), /more than one column/);
assert.throws(() => compareSnapshots(before, header + '1,"unclosed'), /quoted field/);
const reverse = compareSnapshots(before.replaceAll('2026-10-02', '2026-10-25'), before);
assert.ok(reverse.warnings.some(w => w.includes('older Data As Of')));
const formula = compareSnapshots('permit_number,status\n1,filed\n', 'permit_number,status\n1,=HYPERLINK(1)\n');
const exported = parseCSV(comparisonCSV(formula.rows, '2026-10-26T00:00:00Z'));
assert.equal(exported[1][exported[0].indexOf('later_status')], "'=HYPERLINK(1)");
assert.equal(exported[1][exported[0].indexOf('purchasing_status')], 'UNVERIFIED');
const dated = compareSnapshots(fs.readFileSync(new URL('./earlier-example.csv', import.meta.url), 'utf8'), fs.readFileSync(new URL('./later-example.csv', import.meta.url), 'utf8'));
assert.equal(dated.counts.changed, 2); assert.equal(dated.counts.unchanged, 1);
assert.equal(dated.rows.find(r => r.permit_number === '202608196841').before.status, 'filed');
assert.equal(dated.rows.find(r => r.permit_number === '202608196841').after.status, 'issued');
assert.deepEqual(dated.rows.find(r => r.permit_number === '202610079164').changed_fields, ['description']);
assert.equal(dated.rows.find(r => r.permit_number === '202609148084').kind, 'unchanged');
console.log('PASS: actual dated status change, unmatched records, duplicates, missing IDs, primary-address exclusions, shared schema, date precision, reversed source dates and CSV formula safety.');
