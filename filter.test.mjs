import assert from 'node:assert/strict';
import fs from 'node:fs';
import { parseCSV, reviewCSV, exportCSV, isoDay } from './finder-core.mjs';
const fixture = fs.readFileSync(new URL('./filter-examples.csv',import.meta.url),'utf8');
const review = reviewCSV(fixture);
assert.equal(review.rows.length,4);
assert.equal(review.rows.find(r=>r.permit_number==='202610159474').reference_permit_candidates[0],'202609037630');
assert.match(review.rows.find(r=>r.permit_number==='202610199583').scope_review,/Cabinet/);
assert.equal(reviewCSV(fixture,{mode:'equipment'}).rows.length,2);
assert.ok(!reviewCSV(fixture,{mode:'equipment'}).rows.some(r=>r.permit_number==='202610229781'),'HVAC equipment-room wording alone must not pass the kitchen-equipment rule');
assert.equal(reviewCSV(fixture,{since:'2026-10-20'}).rows.length,2);
assert.ok(review.rows.every(r=>r.purchasing_status==='UNVERIFIED'));
const duplicate = fixture + fixture.split('\r\n')[1] + '\r\n';
assert.equal(reviewCSV(duplicate).rows.length,4);
assert.equal(reviewCSV(duplicate).stats.duplicateRows,1);
const missingDates = reviewCSV('Permit Number,Description,Filed Date\n1,"new restaurant",not-a-date\n');
assert.equal(missingDates.rows.length,1);
assert.equal(reviewCSV('Permit Number,Description,Filed Date\n1,"new restaurant",not-a-date\n',{since:'2026-10-01'}).rows.length,0);
assert.equal(isoDay('02/30/2026'),'');
assert.equal(isoDay('10/22/2026 1:20 PM'),'2026-10-22');
assert.throws(()=>reviewCSV('Permit Number,Description\n1,restaurant'),/Required columns/);
assert.throws(()=>reviewCSV('Permit Number,Description,Filed Date\n1,"unterminated'),/quoted field/);
assert.throws(()=>reviewCSV('Permit Number,Description,Filed Date\n1,restaurant,2026-10-22,extra'),/different number/);
assert.deepEqual(parseCSV('a,b\r\n"two\nlines","a ""quote"""\r\n'),[['a','b'],['two\nlines','a "quote"']]);
const malicious = reviewCSV('Permit Number,Description,Filed Date,Address\n001,"restaurant, <img src=x onerror=alert(1)>",2026-10-22,=1+1');
const exported = parseCSV(exportCSV(malicious,'2026-10-26T00:00:00Z'));
assert.equal(exported[1][0],'001');
assert.equal(exported[1][1],"'=1+1");
assert.equal(exported[1].at(-1),'2026-10-26T00:00:00Z');
assert.equal(parseCSV(exportCSV(review,'2026-10-26T00:00:00Z')).length,5);
const equipment = fs.readFileSync(new URL('./equipment-examples.csv',import.meta.url),'utf8');
for (const [mode, id] of [['hood','202609037630'],['refrigeration','202609148084'],['coffee','202608196841']]) {
  const r = reviewCSV(equipment,{mode});
  assert.deepEqual(r.rows.map(row=>row.permit_number),[id]);
  assert.equal(r.rows[0].scope_filter,mode);
  assert.equal(r.rows[0].purchasing_status,'UNVERIFIED');
  const exported = parseCSV(exportCSV(r,'2026-10-26T00:00:00Z'));
  assert.equal(exported[1][exported[0].indexOf('scope_filter')],mode);
}
assert.deepEqual(reviewCSV(equipment,{mode:'coffee'}).rows.map(r=>r.data_as_of),['2026-10-20']);
assert.deepEqual(reviewCSV(equipment,{mode:'refrigeration'}).rows.map(r=>r.data_as_of),['2026-10-01']);
assert.equal(reviewCSV(equipment,{mode:'hood',since:'2026-10-01'}).rows.length,0);
assert.equal(reviewCSV(fixture,{mode:'coffee'}).rows.length,1,'Cabinet-only coffee-shop work must not pass a trade mode.');
const noise = 'Permit Number,Description,Filed Date\n1,laboratory fume hood replacement,2026-10-01\n2,residential kitchen exhaust,2026-10-01\n3,restaurant HVAC equipment room,2026-10-01';
assert.equal(reviewCSV(noise,{mode:'hood'}).rows.length,0);
assert.equal(reviewCSV(noise,{mode:'refrigeration'}).rows.length,0);
assert.throws(()=>reviewCSV(fixture,{mode:'arbitrary'}),/supported scope/);
console.log('PASS: original four-row behavior and CSV safety preserved; three trade subsets, dated evidence, selected-mode export and unrelated/cabinet exclusions verified.');
